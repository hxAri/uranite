TEST_F( IntegrationTest, BorrowCheckerDoubleFree ) {
	IntegrationTest::CompileResult compiled = this->compileShouldFail(
		"package main\n"
		"class Box:\n"
		"    public I64 value\n"
		"public function main() -> I32:\n"
		"    Box b = new Box()\n"
		"    delete b\n"
		"    delete b\n"
		"    return 0\n"
	);
	EXPECT_NE( compiled.status, 0 );
	EXPECT_NE( compiled.output.find( "double free" ), std::string::npos );
}

