/**
 * @class IntegrationTest
 * @brief Test fixture for end-to-end integration testing of the Uranite compiler.
 * * This fixture manages the lifecycle of compilation testing by creating an isolated 
 * temporary directory, executing the compiler binary via shell commands, capturing standard 
 * outputs/errors, and ensuring proper sandbox cleanup after each test case.
 */
class IntegrationTest : public ::testing::Test {
	
	protected:
		
		/**
		 * @struct CompileResult
		 * @brief Encapsulates the execution feedback from a spawned shell process.
		 */
		struct CompileResult {
			std::string output;  ///< Combined standard output and standard error stream data.
			int status;          ///< The process exit status code (0 for success).
		};
		
		/** @brief Path to the target compiler executable binary. */
		std::string compiler;
		
		/** @brief Isolated temporary directory path used for reading/writing compilation artifacts. */
		std::string temporary = "/tmp/uranite-test-integration";
		
		/**
		 * @brief Prepares the test environment before executing a test case.
		 * * Initializes the compiler binary path and guarantees the existence of 
		 * the temporary sandbox directory via shell invocation.
		 */
		void SetUp() override {
			this->compiler = "./build/uranite";
			system( fmt::format( "mkdir -p {}", this->temporary ).c_str() );
		}
		
		/**
		 * @brief Cleans up the test environment after a test case finishes execution.
		 * * Recursively purges the temporary sandbox directory to prevent artifact 
		 * leakage between test boundaries.
		 */
		void TearDown() override {
			system( fmt::format( "rm -rf {}", this->temporary ).c_str() );
		}
		
		/**
		 * @brief Writes a raw string of source code into a physical file inside the sandbox.
		 * @param name The desired source filename (e.g., "main.urn").
		 * @param code The complete payload of the source program code.
		 */
		void writeSource( const std::string& name, const std::string& code ) {
			std::ofstream f( fmt::format( "{}/{}", this->temporary, name ) );
			f << code;
		}
		
		/**
		 * @brief Invokes the compiler binary to build an executable from the given source file.
		 * @param name The filename of the source code stored in the sandbox.
		 * @return CompileResult The status code and compiler diagnostics output.
		 */
		CompileResult compile( const std::string& name ) {
			std::string src( fmt::format( "{}/{}", this->temporary, name ) );
			std::string bin( fmt::format( "{}/out", this->temporary ) );
			std::string cmd( fmt::format(  "{} {} -o {} 2>&1", this->compiler, src, bin ) );
			return this->runCmd( cmd );
		}
		
		/**
		 * @brief Executes the compiled binary artifact generated by the compile phase.
		 * @return CompileResult The runtime exit code and stdout/stderr output of the compiled program.
		 */
		CompileResult run() {
			return this->runCmd( fmt::format( "{}/out 2>&1", this->temporary ) );
		}
		
		/**
		 * @brief Helper to write, compile, and execute a program for positive validation tests.
		 * * If the compilation phase fails, it aborts immediately and returns the compilation failure details.
		 * @param name The designated source file name.
		 * @param code The source code text.
		 * @return CompileResult The runtime results if compilation succeeds, otherwise the compilation errors.
		 */
		CompileResult compileAndRun( const std::string& code ) {
			std::string filename( "test-integration.urn" );
			this->writeSource( filename, code );
			CompileResult cr = this->compile( filename );
			if( cr.status != 0 ) {
				return cr;
			}
			return this->run();
		}
		
		/**
		 * @brief Helper designed for negative testing where compilation is expected to fail.
		 * @param name The designated source file name.
		 * @param code The invalid source code text expected to trigger errors.
		 * @return CompileResult The compilation result containing expected error messages and non-zero code.
		 */
		CompileResult compileShouldFail( const std::string& code ) {
			std::string filename( "test-integration.urn" );
			this->writeSource( filename, code );
			return this->compile( filename );
		}
		
		/**
		 * @brief Helper to compile and run a program, aggregating both compile-time and runtime outputs.
		 * @param name The designated source file name.
		 * @param code The source code text.
		 * @return CompileResult Combined outputs from both compilation and runtime execution logs.
		 */
		CompileResult compileAndRunFull( const std::string& code ) {
			std::string filename( "test-integration.urn" );
			this->writeSource( filename, code );
			CompileResult cr = this->compile( filename );
			if( cr.status != 0 ) {
				return cr;
			}
			CompileResult rr = this->run();
			rr.output = cr.output + rr.output;
			return rr;
		}
		
	private:
		
		/**
		 * @brief Low-level utility to execute a shell command using an sub-process pipe.
		 * * Captures the target output safely chunk-by-chunk and extracts the proper 
		 * native macro translation of the shell exit status.
		 * @param cmd The raw shell command string to execute.
		 * @return CompileResult Synchronous results of the command execution.
		 */
		CompileResult runCmd( const std::string& cmd ) {
			CompileResult result;
			FILE* pipe = popen( cmd.c_str(), "r" );
			if( !pipe ) { 
				result.status = -1; 
				return result; 
			}
			char buf[256];
			while( fgets( buf, sizeof( buf ), pipe ) ) {
				result.output += buf;
			}
			result.status = pclose( pipe );
			result.status = WEXITSTATUS( result.status );
			return result;
		}
	
};

